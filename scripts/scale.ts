// Writes the Lasik scale into palette.toml: every hue in steps 50-950, each step a contrast against
// OBSIDIAN. The hand-picked base colors stay exactly as they are, at their nearest step; the other
// steps are calculated from them (see README.md, "The scale").
//
// usage (from the palette folder): deno run --allow-read --allow-write scripts/scale.ts
const FILE = new URL("../palette.toml", import.meta.url).pathname
const BEGIN = "# ---- scale: generated by scripts/scale.ts, don't edit by hand ----"
const END = "# ---- end of scale ----"

// step -> contrast on OBSIDIAN. 600 and lighter is AA text (4.5:1), 500 and lighter AAA (7:1),
// 700 a visible UI line (3:1), 800 and darker backgrounds.
const STEPS: [number, number][] = [[50, 17.5], [100, 16], [200, 14.5], [300, 12.5], [400, 10], [500, 7], [600, 4.5], [700, 3], [800, 2], [900, 1.5], [950, 1.25]]
// the hues with a hand-picked base color (their legacy names below)
const HUES = ["RED", "ROSE", "PEACH", "APRICOT", "YELLOW", "GREEN", "TEAL", "SAPPHIRE", "SKY", "BLUE", "MAUVE", "PINK"]
// NEUTRAL: the text, surfaces and lines, made from the hand-picked PERIWINKLE (#a8bcfc, very easy to read on
// OBSIDIAN). SLATE, LAVENDER, PERIWINKLE and SILVER became NEUTRAL steps (2026-10-24).
const NEUTRAL_BASE = "PERIWINKLE"

let text = await Deno.readTextFile(FILE)
const palette: Record<string, string> = {}
for (const m of text.matchAll(/^([A-Z0-9_]+)\s*=\s*"(#[0-9a-fA-F]{6})"/gm)) palette[m[1]] = m[2].toLowerCase()

// ---- color math: WCAG contrast, OKLCH <-> sRGB
const channel = (v: number) => { const c = v / 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4 }
const linear = (hex: string) => [1, 3, 5].map((i) => channel(parseInt(hex.slice(i, i + 2), 16)))
const luminance = (hex: string) => { const [r, g, b] = linear(hex); return 0.2126 * r + 0.7152 * g + 0.0722 * b }
const contrast = (a: string, b: string) => { const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05) }
function oklch(hex: string) {
  const [r, g, b] = linear(hex)
  const [l, m, s] = [0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b, 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b, 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b].map(Math.cbrt)
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s
  return { L, C: Math.hypot(A, B), H: ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360 }
}
function toLinear(L: number, C: number, H: number) {
  const a = C * Math.cos((H * Math.PI) / 180), b = C * Math.sin((H * Math.PI) / 180)
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3, m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3, s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  return [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s]
}
const inGamut = (rgb: number[]) => rgb.every((v) => v >= -0.0005 && v <= 1.0005)
const toHex = (rgb: number[]) => "#" + rgb.map((v) => { const c = Math.min(1, Math.max(0, v)); return Math.round((c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055) * 255).toString(16).padStart(2, "0") }).join("")
/** lightness L at this hue, with as much of chroma C as a normal screen (sRGB) can show */
function atL(L: number, C: number, H: number) {
  if (inGamut(toLinear(L, C, H))) return toHex(toLinear(L, C, H))
  let lo = 0, hi = C
  for (let i = 0; i < 30; i++) { const mid = (lo + hi) / 2; inGamut(toLinear(L, mid, H)) ? lo = mid : hi = mid }
  return toHex(toLinear(L, lo, H))
}
/** the color of this hue with the target contrast on OBSIDIAN. Lighter than baseL: chroma C. Darker: chroma
 *  shrinks with lightness (C × L / baseL), like mixing into the background, so dark steps stay calm. */
function atContrast(C: number, H: number, target: number, baseL: number) {
  const chroma = (L: number) => (L >= baseL ? C : (C * L) / baseL)
  let lo = 0, hi = 1
  for (let i = 0; i < 40; i++) { const mid = (lo + hi) / 2; contrast(atL(mid, chroma(mid), H), palette.OBSIDIAN) < target ? lo = mid : hi = mid }
  return atL(hi, chroma(hi), H)
}
const nearestStep = (ratio: number) => STEPS.reduce((best, s) => (Math.abs(Math.log(s[1] / ratio)) < Math.abs(Math.log(best[1] / ratio)) ? s : best))[0]

// ---- the scale
const lines = [BEGIN, "#", "# NAME_<step>: step 50 is the lightest, 950 the darkest. Target contrast on OBSIDIAN per step:", `# ${STEPS.map(([s, t]) => `${s}: ${t}`).join(", ")}.`, "# The actual contrast is in each comment. \"hand-picked\" = the base color, kept exactly; everything", "# else is generated (formula in README.md, \"The scale\").", ""]
const hues: [string, number, number, number, string][] = [["NEUTRAL", NEUTRAL_BASE], ...HUES.map((h) => [h, h])].map(([name, base]) => {
  const k = oklch(palette[base])
  return [name, k.C, k.H, k.L, palette[base]]
})
for (const [name, C, H, baseL, base] of hues) {
  const anchor = nearestStep(contrast(base, palette.OBSIDIAN))
  lines.push(`# ${name}: hue ${H.toFixed(0)}°, chroma ${C.toFixed(3)}, hand-picked ${base} at ${anchor}${name === "NEUTRAL" ? " (PERIWINKLE)" : ""}`)
  for (const [step, target] of STEPS) {
    const hex = step === anchor ? base : atContrast(C, H, target, baseL)
    const key = `${name}_${step}`.padEnd(15)
    lines.push(`${key} = "${hex}"  # ${contrast(hex, palette.OBSIDIAN).toFixed(2)}:1${step === anchor ? ", hand-picked" : ""}`)
  }
  lines.push("")
}
lines.push(END)
const block = lines.join("\n")

text = text.includes(BEGIN)
  ? text.replace(new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`), block)
  : text.replace(/\n(OBSIDIAN\s*=)/, `\n${block}\n\n$1`)
await Deno.writeTextFile(FILE, text)
console.log(`wrote ${hues.length} scales × ${STEPS.length} steps into palette.toml`)
